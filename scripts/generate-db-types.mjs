import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync, renameSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const target = new URL("../types/database.types.ts", import.meta.url);
const temporary = new URL("../types/database.types.ts.tmp", import.meta.url);
const result = spawnSync(
  "supabase",
  ["gen", "types", "typescript", "--local", "--schema", "public"],
  { cwd: root, encoding: "utf8", shell: false },
);
if (
  result.error ||
  result.status !== 0 ||
  !result.stdout.includes("export type Database")
) {
  process.stderr.write(
    "No se generaron tipos. PostgreSQL local debe estar disponible y migrado. El artefacto anterior se conserva.\n",
  );
  process.exit(1);
}
try {
  mkdirSync(new URL("../types/", import.meta.url), { recursive: true });
  writeFileSync(
    temporary,
    "// Generated by Supabase CLI. Do not edit.\n" +
      result.stdout.replace(/[ \t]+$/gm, ""),
  );
  renameSync(temporary, target);
} finally {
  rmSync(temporary, { force: true });
}
